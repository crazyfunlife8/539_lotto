let currentLang = (function() {
  try { return localStorage.getItem('lang') || 'zh-tw'; } catch(e) { return 'zh-tw'; }
})();

function t(key, vars) {
  const dict = T[currentLang] || T['zh-tw'];
  let s = (dict && dict[key] !== undefined) ? dict[key] : (T['zh-tw'][key] || key);
  if (vars) {
    Object.keys(vars).forEach(k => { s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]); });
  }
  return s;
}

function applyLang() {
  /* text nodes */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  /* html nodes (contain markup) */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  /* lang button highlight */
  document.querySelectorAll('[data-lang-btn]').forEach(btn => {
    const active = btn.dataset.langBtn === currentLang;
    if (active) {
      btn.style.background = 'rgba(196,154,42,0.15)';
      btn.style.color = '#c49a2a';
      btn.style.border = '1px solid rgba(196,154,42,0.3)';
      btn.style.fontWeight = '700';
    } else {
      btn.style.background = 'transparent';
      btn.style.color = '#5a4a35';
      btn.style.border = '';
      btn.style.fontWeight = '';
    }
  });
  /* html lang attribute */
  const htmlEl = document.documentElement;
  if (currentLang === 'zh-tw') htmlEl.lang = 'zh-TW';
  else if (currentLang === 'zh-cn') htmlEl.lang = 'zh-CN';
  else htmlEl.lang = 'en';
}

function setLang(lang) {
  if (!T[lang]) return;
  currentLang = lang;
  try { localStorage.setItem('lang', lang); } catch(e) {}
  applyLang();
  /* re-render dynamic content if page functions exist */
  if (typeof renderCart   === 'function') renderCart();
  if (typeof renderSaved  === 'function') renderSaved();
  if (typeof renderBalls  === 'function') renderBalls();
}

/* auto-apply on DOM ready */
document.addEventListener('DOMContentLoaded', applyLang);
